"""Operational transformation algorithm for concurrent text edits."""

from typing import Tuple

from app.engine.operation import OpComponent, OpKind, TextOperation


def transform(
    op1: TextOperation, op2: TextOperation, priority: bool = True
) -> Tuple[TextOperation, TextOperation]:
    """Transform two concurrent operations against each other.

    Given operations op1 and op2 originating from the same document state,
    produce (op1_prime, op2_prime) such that:
        apply(apply(S, op1), op2_prime) == apply(apply(S, op2), op1_prime)

    Args:
        op1: Operation generated by client 1.
        op2: Operation generated by client 2.
        priority: Tie-breaking flag if both insert at the same location.
            True gives precedence to op1, False gives precedence to op2.

    Returns:
        Tuple of (op1_prime, op2_prime).
    """
    if op1.base_length != op2.base_length:
        raise ValueError(
            f"Cannot transform operations with mismatched base_length: "
            f"{op1.base_length} != {op2.base_length}"
        )

    op1_prime = TextOperation()
    op2_prime = TextOperation()

    comps1 = [OpComponent(c.kind, c.value) for c in op1.components]
    comps2 = [OpComponent(c.kind, c.value) for c in op2.components]

    i = 0
    j = 0

    while i < len(comps1) or j < len(comps2):
        c1 = comps1[i] if i < len(comps1) else None
        c2 = comps2[j] if j < len(comps2) else None

        # Case 1: Both operations insert at the exact same location
        if (
            c1 is not None
            and c2 is not None
            and c1.kind == OpKind.INSERT
            and c2.kind == OpKind.INSERT
        ):
            if priority:
                text1 = str(c1.value)
                op1_prime.insert(text1)
                op2_prime.retain(len(text1))
                i += 1
            else:
                text2 = str(c2.value)
                op1_prime.retain(len(text2))
                op2_prime.insert(text2)
                j += 1
            continue

        # Case 2: op1 inserts text
        if c1 is not None and c1.kind == OpKind.INSERT:
            text1 = str(c1.value)
            op1_prime.insert(text1)
            op2_prime.retain(len(text1))
            i += 1
            continue

        # Case 3: op2 inserts text
        if c2 is not None and c2.kind == OpKind.INSERT:
            text2 = str(c2.value)
            op1_prime.retain(len(text2))
            op2_prime.insert(text2)
            j += 1
            continue

        if c1 is None or c2 is None:
            raise ValueError(
                "Cannot transform operations: mismatched component lengths"
            )

        len1 = int(c1.value)
        len2 = int(c2.value)
        min_len = min(len1, len2)

        if c1.kind == OpKind.RETAIN and c2.kind == OpKind.RETAIN:
            op1_prime.retain(min_len)
            op2_prime.retain(min_len)
        elif c1.kind == OpKind.RETAIN and c2.kind == OpKind.DELETE:
            op2_prime.delete(min_len)
        elif c1.kind == OpKind.DELETE and c2.kind == OpKind.RETAIN:
            op1_prime.delete(min_len)
        elif c1.kind == OpKind.DELETE and c2.kind == OpKind.DELETE:
            # Both deleted the same characters; neither emits
            pass

        if len1 > min_len:
            c1.value = len1 - min_len
        else:
            i += 1

        if len2 > min_len:
            c2.value = len2 - min_len
        else:
            j += 1

    return op1_prime, op2_prime
